// GV_StrCode — 16-bit rotating hash from libgv/strcode.c.
// Use to compute STRID for ASCII strings (e.g. 'chara' -> 0x9906).
function gcxStrCode(s) {
  var h = 0;
  for (var i = 0; i < s.length; i++) {
    var c = s.charCodeAt(i);
    h = ((h << 5) | (h >> 11)) & 0xFFFF;
    h = (h + c) & 0xFFFF;
  }
  return h;
}

